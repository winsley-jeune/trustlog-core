// Generates 50 seed receipts for ARIA-7 with proper chain hashes.
// Run: npx tsx scripts/generate-seed-receipts.ts >> supabase/seed.sql
// Each chain_hash = SHA-256(receipt JSON + prev chain_hash)

import { createHash } from 'crypto'

const AGENT_ID = '10000000-0000-0000-0000-000000000001'

const categories = [
  'data-analysis', 'research', 'code-generation', 'content-creation',
  'automation', 'data-analysis', 'research', 'data-analysis',
]

const taskDescs = [
  'Quarterly revenue analysis for Q1 2026',
  'Competitive landscape research — AI infrastructure',
  'ETL pipeline optimization script',
  'Executive summary: market sizing report',
  'Automated data quality checks',
  'Cohort analysis: customer retention',
  'Literature review: federated learning',
  'Financial model: Series B projections',
]

function sha256(content: string): string {
  return createHash('sha256').update(content).digest('hex')
}

let prevHash = 'GENESIS'
const receipts: string[] = []

console.log('')
console.log('-- ─────────────────────────────────────────────────────────────')
console.log('-- SEED RECEIPTS FOR ARIA-7 (50 receipts)')
console.log('-- Generated by scripts/generate-seed-receipts.ts')
console.log('-- ─────────────────────────────────────────────────────────────')
console.log('')

for (let i = 1; i <= 50; i++) {
  const category = categories[(i - 1) % categories.length]
  const taskDesc = taskDescs[(i - 1) % taskDescs.length]
  const durationMs = 800 + Math.floor(Math.random() * 2000)
  const status = i === 23 ? 'partial' : i === 37 ? 'failure' : 'success'
  const inputHash = sha256(`aria7-input-${i}`)
  const outputHash = sha256(`aria7-output-${i}`)

  const receiptData = JSON.stringify({
    agent_id: AGENT_ID,
    input_hash: inputHash,
    output_hash: outputHash,
    category,
    duration_ms: durationMs,
    status,
    chain_position: i,
    prev_chain_hash: prevHash,
  })

  const chainHash = sha256(receiptData)

  // Generate a deterministic UUID for the receipt
  const receiptId = `20000000-0000-0000-0000-${String(i).padStart(12, '0')}`

  console.log(`INSERT INTO public.task_receipts (id, agent_id, task_description, category, input_hash, output_hash, duration_ms, status, chain_hash, prev_chain_hash, chain_position, oracle_verified, oracle_score, created_at) VALUES ('${receiptId}', '${AGENT_ID}', '${taskDesc.replace(/'/g, "''")}', '${category}', '${inputHash}', '${outputHash}', ${durationMs}, '${status}', '${chainHash}', '${prevHash}', ${i}, ${i <= 40 ? 'true' : 'false'}, ${i <= 40 ? (status === 'success' ? 85 + Math.floor(Math.random() * 15) : 30 + Math.floor(Math.random() * 30)) : 'null'}, now() - interval '${50 - i} hours');`)

  prevHash = chainHash
}

// Update ARIA-7's chain head and length
const lastReceiptId = `20000000-0000-0000-0000-${String(50).padStart(12, '0')}`
console.log('')
console.log(`UPDATE public.agents SET chain_head_id = '${lastReceiptId}', chain_length = 50 WHERE id = '${AGENT_ID}';`)
